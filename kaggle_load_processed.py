"""
kaggle_load_processed.py
========================
Run ONCE on Kaggle after attaching the "revrag-processed" dataset.

  !python kaggle_load_processed.py

What it does:
  - Copies the preprocessed JSON files from /kaggle/input/revrag-processed/
    into /kaggle/working/data/processed/ (fast symlink if possible)
  - Writes kaggle_config.py pointing all paths to the working dir
  - Installs Python dependencies (torch, faiss-cpu, etc.)

After this, run:
  !python train.py --processed_dir /kaggle/working/data/processed
  !python evaluate.py --processed_dir /kaggle/working/data/processed
"""
import os, shutil, subprocess, sys
from pathlib import Path

WORKING_DIR    = Path("/kaggle/working")
PROCESSED_SRC  = Path("/kaggle/input/revrag-processed/revrag_processed")
PROCESSED_DST  = WORKING_DIR / "data" / "processed"
OUT_DIR        = WORKING_DIR / "outputs"

# ── Validate dataset is attached ────────────────────────────────────────────
if not Path("/kaggle/input/revrag-processed").exists():
    print("ERROR: Dataset 'revrag-processed' not found at /kaggle/input/revrag-processed/")
    print("       Attach it via Add Data → revrag-processed in the Kaggle notebook UI.")
    sys.exit(1)

# ── Copy / symlink processed files ──────────────────────────────────────────
print(f"Source : {PROCESSED_SRC}")
print(f"Dest   : {PROCESSED_DST}")
if PROCESSED_DST.exists():
    print("  Already exists — skipping copy.")
else:
    try:
        PROCESSED_DST.symlink_to(PROCESSED_SRC)
        print("  Symlinked.")
    except Exception:
        print("  Symlink failed — copying (may take a moment)...")
        shutil.copytree(str(PROCESSED_SRC), str(PROCESSED_DST))
        print("  Copied.")

OUT_DIR.mkdir(parents=True, exist_ok=True)

# ── Install dependencies ─────────────────────────────────────────────────────
print("\nInstalling Python packages ...")
pkgs = [
    "torch", "transformers", "faiss-cpu",
    "rank_bm25", "sentence_transformers",
    "matplotlib", "numpy", "scikit-learn",
    "datasets",
]
subprocess.run([sys.executable, "-m", "pip", "install"] + pkgs + ["-q"], check=False)
print("  OK")

# ── Write kaggle_config.py ────────────────────────────────────────────────────
cfg_path = WORKING_DIR / "kaggle_config.py"
cfg_path.write_text(f"""\
# kaggle_config.py  — auto-generated by kaggle_load_processed.py
# Import before anything else:  import kaggle_config
import src.config as _cfg
from pathlib import Path

_PROC = Path("{PROCESSED_DST}")
_OUT  = Path("{OUT_DIR}")

_cfg.CFG.data.data_dir         = _PROC.parent
_cfg.CFG.data.processed_dir    = _PROC
_cfg.CFG.out_dir               = _OUT
_OUT.mkdir(parents=True, exist_ok=True)
print("[kaggle_config] Paths configured for Kaggle (pre-processed mode).")
""", encoding="utf-8")
print(f"\nWrote {cfg_path}")

# ── Summary ───────────────────────────────────────────────────────────────────
print("\n" + "=" * 60)
print("Setup complete. Preprocessed files:")
for p in sorted(PROCESSED_DST.rglob("*.json")):
    mb = p.stat().st_size / 1e6
    print(f"  {p.relative_to(PROCESSED_DST)}  ({mb:.1f} MB)")
print("=" * 60)
print("\nNext steps:")
print("  !python train.py    --processed_dir", PROCESSED_DST)
print("  !python evaluate.py --processed_dir", PROCESSED_DST)
print("=" * 60)
