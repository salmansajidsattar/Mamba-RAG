"""
kaggle_setup_from_dataset.py
=============================
Run this in your Kaggle notebook AFTER attaching the revrag-datasets dataset.

The dataset will be mounted at:  /kaggle/input/revrag-datasets/

This script copies everything to /kaggle/working/data/ and writes kaggle_config.py.

Usage (Kaggle notebook cell):
    !python kaggle_setup_from_dataset.py
"""
import os, shutil, sys, subprocess
from pathlib import Path

INPUT_DIR = Path("/kaggle/input/revrag-datasets")
WORK_DIR  = Path("/kaggle/working")
DATA_DIR  = WORK_DIR / "data"
HF_DIR    = DATA_DIR / "hf_cache"

print("=" * 60)
print("RevRAG - Setup from Kaggle Dataset")
print(f"Input : {INPUT_DIR}")
print(f"Output: {DATA_DIR}")
print("=" * 60)

# Verify dataset is attached
if not INPUT_DIR.exists():
    print("\nERROR: Dataset not found at", INPUT_DIR)
    print("\nFix:")
    print("  1. In your Kaggle notebook, click 'Add Data' (right panel)")
    print("  2. Search for 'revrag-datasets'")
    print("  3. Click Add, then re-run this cell")
    sys.exit(1)

print("\nDataset contents:")
for p in sorted(INPUT_DIR.rglob("*"))[:20]:
    if p.is_file():
        print(f"  {p.relative_to(INPUT_DIR)}")
print("  ...")


# ---------------------------------------------------------------------------
# Install dependencies
# ---------------------------------------------------------------------------
def install_deps():
    print("\n[1] Installing dependencies ...")
    pkgs = [
        "datasets", "huggingface_hub", "transformers",
        "faiss-cpu", "rank_bm25", "sentence_transformers",
        "matplotlib", "numpy", "scikit-learn",
    ]
    subprocess.run([sys.executable, "-m", "pip", "install"] + pkgs + ["-q"],
                   check=False)
    print("  OK")


# ---------------------------------------------------------------------------
# Copy ContractNLI
# ---------------------------------------------------------------------------
def setup_contractnli():
    print("\n[2] ContractNLI ...")
    src_dir = INPUT_DIR / "contractnli"
    dst_dir = DATA_DIR / "contractnli" / "resources" / "contract-nli"
    dst_dir.mkdir(parents=True, exist_ok=True)

    for split in ("train", "dev", "test"):
        src = src_dir / f"{split}.json"
        dst = dst_dir / f"{split}.json"
        if dst.exists():
            print(f"  Already exists: {split}.json")
            continue
        if src.exists():
            shutil.copy2(src, dst)
            print(f"  OK {split}.json ({src.stat().st_size/1e6:.1f} MB)")
        else:
            print(f"  MISSING in dataset: {src}")


# ---------------------------------------------------------------------------
# Symlink or copy HF cache
# ---------------------------------------------------------------------------
def setup_hf_cache():
    print("\n[3] HF cache ...")
    src_hf = INPUT_DIR / "hf_cache"
    if not src_hf.exists():
        print("  No hf_cache folder found in dataset")
        return

    HF_DIR.mkdir(parents=True, exist_ok=True)

    # Point HF env vars at dataset directly (read-only is fine for loading)
    # Copy only if needed — avoids duplicating 500MB
    for cache_dir in src_hf.iterdir():
        if not cache_dir.is_dir():
            continue
        dst = HF_DIR / cache_dir.name
        if dst.exists():
            print(f"  Already exists: {cache_dir.name}")
            continue
        try:
            # Try symlink first (no disk copy)
            dst.symlink_to(cache_dir)
            print(f"  Symlinked: {cache_dir.name}")
        except Exception:
            # Fall back to copy
            shutil.copytree(str(cache_dir), str(dst))
            print(f"  Copied: {cache_dir.name}")


# ---------------------------------------------------------------------------
# Set HF env vars to point at working data dir
# ---------------------------------------------------------------------------
def set_env():
    print("\n[4] Setting HF environment variables ...")
    for key, val in [
        ("HF_HOME",                        str(HF_DIR)),
        ("HF_DATASETS_CACHE",              str(HF_DIR)),
        ("HUGGINGFACE_HUB_CACHE",          str(HF_DIR)),
        ("TRANSFORMERS_CACHE",             str(HF_DIR)),
        ("HF_HUB_DISABLE_SYMLINKS_WARNING","1"),
    ]:
        os.environ[key] = val
    print("  OK")


# ---------------------------------------------------------------------------
# Write kaggle_config.py
# ---------------------------------------------------------------------------
def write_kaggle_config():
    print("\n[5] Writing kaggle_config.py ...")
    lines = [
        "# kaggle_config.py - auto-generated by kaggle_setup_from_dataset.py",
        "# Usage: import kaggle_config  (before from src.config import CFG)",
        "import os, src.config as _cfg",
        "from pathlib import Path",
        f'_DATA = Path("{DATA_DIR}")',
        f'_HF   = Path("{HF_DIR}")',
        '_CNLI = _DATA / "contractnli" / "resources" / "contract-nli"',
        "_cfg.CFG.data.data_dir        = _DATA",
        "_cfg.CFG.data.hf_cache        = _HF",
        "_cfg.CFG.data.hf_cache_dir    = _HF",
        "_cfg.CFG.data.contractnli_dir = _CNLI",
        "_cfg.CFG.data.cuad_cache      = _HF",
        "_cfg.CFG.data.multihop_cache  = _HF",
        "_cfg.CFG.data.loco_cache      = _HF",
        '_cfg.CFG.out_dir              = Path("/kaggle/working/outputs")',
        "_cfg.CFG.out_dir.mkdir(parents=True, exist_ok=True)",
        f'os.environ["HF_HOME"]             = str(_HF)',
        f'os.environ["HF_DATASETS_CACHE"]   = str(_HF)',
        f'os.environ["HUGGINGFACE_HUB_CACHE"]= str(_HF)',
        'print("[kaggle_config] Ready.")',
    ]
    out = WORK_DIR / "kaggle_config.py"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  OK -> {out}")


# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------
def print_summary():
    print("\n" + "=" * 60)
    print("Setup Summary")
    print("=" * 60)
    checks = [
        ("ContractNLI train.json", DATA_DIR / "contractnli/resources/contract-nli/train.json"),
        ("ContractNLI dev.json",   DATA_DIR / "contractnli/resources/contract-nli/dev.json"),
        ("ContractNLI test.json",  DATA_DIR / "contractnli/resources/contract-nli/test.json"),
        ("CUAD cache",             HF_DIR / "datasets--theatticusproject--cuad"),
        ("MultiHopRAG cache",      HF_DIR / "datasets--yixuantt--MultiHopRAG"),
        ("LoCoV1-Documents cache", HF_DIR / "datasets--hazyresearch--LoCoV1-Documents"),
        ("LoCoV1-Queries cache",   HF_DIR / "datasets--hazyresearch--LoCoV1-Queries"),
    ]
    all_ok = True
    for name, path in checks:
        exists = Path(path).exists()
        print(f"  {'OK ' if exists else 'MISSING'} {name}")
        if not exists:
            all_ok = False
    print("=" * 60)
    if all_ok:
        print("All datasets ready.")
        print("Next: !python smoke_test.py")
        print("Then: !python train.py --device cuda")
    else:
        print("Some items missing - check errors above.")
    print("=" * 60)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
install_deps()
setup_contractnli()
setup_hf_cache()
set_env()
write_kaggle_config()
print_summary()
